  var locale = 'zh';

  function interpolate(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, function (_, key) {
      return vars[key] == null ? '' : String(vars[key]);
    });
  }

  function t(key, vars) {
    var table = STRINGS[locale] || STRINGS.zh;
    var raw = (table && table[key]) || STRINGS.zh[key] || key;
    return interpolate(raw, vars);
  }

  function setLocale(next) {
    locale = next === 'en' ? 'en' : 'zh';
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
    }
    return locale;
  }

  function getLocale() {
    return locale;
  }

  function apply(root) {
    if (typeof document === 'undefined') return;
    root = root || document;
    var nodes = root.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute('data-i18n');
      if (!key) continue;
      var attr = el.getAttribute('data-i18n-attr');
      var value = t(key);
      if (attr) el.setAttribute(attr, value);
      else if (el.getAttribute('data-i18n-html') === '1') el.innerHTML = value;
      else el.textContent = value;
    }
    nodes = root.querySelectorAll('[data-i18n-placeholder]');
    for (i = 0; i < nodes.length; i++) {
      nodes[i].setAttribute('placeholder', t(nodes[i].getAttribute('data-i18n-placeholder')));
    }
    nodes = root.querySelectorAll('[data-i18n-title]');
    for (i = 0; i < nodes.length; i++) {
      nodes[i].setAttribute('title', t(nodes[i].getAttribute('data-i18n-title')));
    }
    var title = t('doc.title');
    if (document.title !== title) document.title = title;
    nodes = root.querySelectorAll('[data-set-locale]');
    for (i = 0; i < nodes.length; i++) {
      nodes[i].classList.toggle('is-on', nodes[i].getAttribute('data-set-locale') === locale);
    }
    var sel = root.getElementById ? root.getElementById('set-locale') : document.getElementById('set-locale');
    if (sel && sel.value !== locale) sel.value = locale;
  }

  var api = { t: t, setLocale: setLocale, getLocale: getLocale, apply: apply, STRINGS: STRINGS };
  global.FramespaceI18n = api;
